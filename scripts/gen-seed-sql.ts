// Prints the seats seed SQL (step 3 of backend.md) from the seat plan in lib/seats.ts.
// Run: node --experimental-strip-types scripts/gen-seed-sql.ts
// VIP seats are invitation-only and never sold online, so they are not seeded.
import { SEATS } from "../lib/seats.ts";

const ORDER = ["Platinum", "Gold", "Silver", "Bronze"];

const byCategory = new Map<string, string[]>(ORDER.map((c) => [c, []]));
for (const s of Object.values(SEATS)) {
  if (s.tier === "VIP") continue;
  const ids = byCategory.get(s.tier);
  if (!ids) throw new Error(`Unknown ticket category for seat ${s.id}: ${s.tier}`);
  ids.push(s.id);
}

const categories = [...byCategory];
// One line per seat row keeps the output readable when pasted into the SQL editor.
const list = (ids: string[]) => Object.values(Object.groupBy(ids, (id) => id[0])).map((r) => "    " + r!.map((id) => `'${id}'`).join(",")).join(",\n");
const parts = categories.map(([c, ids]) => `  select '${c}' as tier, unnest(array[\n${list(ids)}\n  ]) as seat_id`);

console.log(`-- Generated by scripts/gen-seed-sql.ts. Per show: ${categories.map(([c, ids]) => `${c} ${ids.length}`).join(", ")} (VIP excluded)
insert into public.seats (show_id, seat_id, tier)
select s.show_id, t.seat_id, t.tier
from (values (1::smallint), (2::smallint)) as s(show_id)
cross join (
${parts.join("\n  union all\n")}
) as t
on conflict (show_id, seat_id) do update set tier = excluded.tier;`);
